pkg load signal;
Fs = 1000;       % Частота дискретизации
A = 1.5;         % Амплитуда первой косинусоиды
B = 1;           % Амплитуда второй косинусоиды
f1 = 50;         % Частота первой косинусоиды
f2 = 100;        % Частота второй косинусоиды
t = 0:1/Fs:1;    % Временной вектор

% Параметры ресемплинга
Fs_new = 3000;   % Новая частота дискретизации
ifreqs = Fs_new / Fs;  % Коэффициент интерполяции

% Генерация сигнала
x = A*cos(2*pi*f1*t) + B*cos(2*pi*f2*t);

% Ресемплинг сигнала
y = resample(x, ifreqs, 1);
ti = 0:1/Fs_new:1;

plot(ti(1:100), y(1:100), 'ro', 'MarkerFaceColor', [1 0 0]);
hold on;
stem(t(1:25), x(1:25), 'MarkerFaceColor', [0 0 1]);
hold off;
legend('Ресемплированный сигнал', 'Исходный сигнал');
xlabel('Время (с)');
ylabel('Амплитуда');

